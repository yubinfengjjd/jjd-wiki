.libPaths(c('E:/research-wiki-env/R-lib-scp/4.5', .libPaths()))
suppressPackageStartupMessages(library(ggplot2))
load('E:/research-wiki-env/sources/scp-2026-10-22/data/pancreas_sub.rda')
